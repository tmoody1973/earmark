import { del } from "@vercel/blob";
import { db } from "../db";

// FR-30 coverage for the M5 stores, to be called by the forget script once it exists (wiring pending), with a person's first name.
//   forgetPersonInEpisodes(firstName) -> { episodesDeleted }
//   forgetPersonInGardenerRuns(firstName) -> { runsDeleted }   (gardener drafts that name the person are deleted)
// Deletes every weekly episode whose script names the person (whole word, any case) and the episode's Blob audio.
// The audio is deleted first; if that fails nothing is removed and the error is thrown so the forget can be re-run.
// A deleted week is simply regenerated by the next runEpisode, from data that no longer holds the person.
export interface ForgetEpisodeDeps {
  sql: ReturnType<typeof db>;
  del: (url: string) => Promise<void>;
}

const escapeRe = (t: string) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const namesRe = (name: string) => new RegExp(`(?<![\\p{L}\\p{N}])${escapeRe(name)}(?![\\p{L}\\p{N}])`, "iu");

export async function forgetPersonInEpisodes(
  firstName: string,
  deps: ForgetEpisodeDeps = { sql: db(), del: (url) => del(url) },
): Promise<{ episodesDeleted: number }> {
  const name = firstName.trim();
  if (!name) return { episodesDeleted: 0 };
  const re = namesRe(name);
  // Loading every script is fine: there is one episode per week.
  const rows = (await deps.sql`select id, script_md, audio_url from episodes`) as { id: number | string; script_md: string; audio_url: string | null }[];
  const hits = rows.filter((r) => re.test(r.script_md));
  for (const r of hits) {
    if (r.audio_url) await deps.del(r.audio_url);
    await deps.sql`delete from episodes where id = ${Number(r.id)}`;
  }
  return { episodesDeleted: hits.length };
}

// Gardener drafts (M5-T12) are model text built from the person's data, so any draft naming them is deleted outright.
// Gardener definitions themselves are the owner's own words and are not touched.
export async function forgetPersonInGardenerRuns(
  firstName: string,
  deps: Pick<ForgetEpisodeDeps, "sql"> = { sql: db() },
): Promise<{ runsDeleted: number }> {
  const name = firstName.trim();
  if (!name) return { runsDeleted: 0 };
  const re = namesRe(name);
  const rows = (await deps.sql`select id, output_md from gardener_runs`) as { id: number | string; output_md: string }[];
  const hits = rows.filter((r) => re.test(r.output_md));
  for (const r of hits) await deps.sql`delete from gardener_runs where id = ${Number(r.id)}`;
  return { runsDeleted: hits.length };
}
